let current = 'it';
export function setLang(code) { current = STRINGS[code] ? code : 'it'; document.documentElement.lang = current; }
export function lang() { return current; }

export function t(key, params = {}) {
  const v = STRINGS[current][key] ?? STRINGS.it[key];
  if (v == null) { console.warn('i18n: manca', key); return key; }
  const s = typeof v === 'function' ? v(params) : v;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
}

export function hasKey(key) { return key in STRINGS.it; }

// Testi statici in index.html marcati con data-i18n.
export function applyStatic() {
  document.title = t('app.name');
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
}

